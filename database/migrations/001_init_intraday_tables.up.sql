CREATE TABLE IF NOT EXISTS tickers (
    ticker_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_symbol VARCHAR(50) NOT NULL UNIQUE,
    ticker_name VARCHAR(255) NOT NULL,
    token VARCHAR(50) NOT NULL,
    scrip_symbol VARCHAR(50) NOT NULL,
    country VARCHAR(10) NOT NULL DEFAULT 'IN',
    timezone VARCHAR(50) NOT NULL DEFAULT 'Asia/Kolkata',
    is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE INDEX IF NOT EXISTS idx_tickers_symbol_lower ON tickers (LOWER(ticker_symbol));
CREATE INDEX IF NOT EXISTS idx_tickers_active ON tickers (is_active);

CREATE TABLE IF NOT EXISTS intraday_prices (
    intraday_price_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_id INT8 NOT NULL REFERENCES tickers(ticker_id) ON DELETE CASCADE,
    timeframe VARCHAR(20) NOT NULL,
    price_time TIMESTAMPTZ NOT NULL,
    price_open NUMERIC(18, 4) NOT NULL,
    price_high NUMERIC(18, 4) NOT NULL,
    price_low NUMERIC(18, 4) NOT NULL,
    price_close NUMERIC(18, 4) NOT NULL,
    volume NUMERIC(18, 4) NOT NULL DEFAULT 0,
    CONSTRAINT uk_intraday_prices UNIQUE (ticker_id, timeframe, price_time)
);

CREATE INDEX IF NOT EXISTS idx_intraday_prices_lookup ON intraday_prices (ticker_id, timeframe, price_time DESC);

CREATE TABLE IF NOT EXISTS live_quotes (
    live_quote_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_id INT8 NOT NULL REFERENCES tickers(ticker_id) ON DELETE CASCADE,
    ltp NUMERIC(18, 4) NOT NULL,
    high NUMERIC(18, 4) NOT NULL,
    low NUMERIC(18, 4) NOT NULL,
    close NUMERIC(18, 4) NOT NULL,
    open NUMERIC(18, 4) NOT NULL,
    quote_time TIMESTAMPTZ NOT NULL,
    change_percent NUMERIC(18, 4) NOT NULL,
    CONSTRAINT uk_live_quotes_ticker UNIQUE (ticker_id)
);

CREATE TABLE IF NOT EXISTS market_holidays (
    market_holiday_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country VARCHAR(10) NOT NULL,
    holiday_date DATE NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_market_holidays_country_date UNIQUE (country, holiday_date)
);

CREATE INDEX IF NOT EXISTS idx_market_holidays_date ON market_holidays (holiday_date ASC);

CREATE TABLE IF NOT EXISTS notification_logs (
    notification_log_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notification_logs_created_at ON notification_logs (created_at DESC);
